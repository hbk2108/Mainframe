-- ============================================================
-- TABLE: HMS.FEEDBACK
-- ============================================================
CREATE TABLE HMS.FEEDBACK (
    FDBK_ID       INTEGER        NOT NULL GENERATED ALWAYS AS IDENTITY
                                   (START WITH 1 INCREMENT BY 1 CACHE 20),
    PATIENT_ID    INTEGER        NOT NULL,
    FDBK_MESSAGE  VARCHAR(2000)  NOT NULL,
    FDBK_DATE     DATE           NOT NULL,
    FDBK_STATUS   CHAR(10)       NOT NULL DEFAULT 'UNREAD',
    CREATED_AT    TIMESTAMP      NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_FEEDBACK PRIMARY KEY (FDBK_ID),
    CONSTRAINT FK_FDBK_PAT FOREIGN KEY (PATIENT_ID)
                           REFERENCES HMS.PATIENTS(PATIENT_ID)
                           ON DELETE RESTRICT,
    CONSTRAINT CK_FDBK_STATUS CHECK (FDBK_STATUS IN ('UNREAD', 'READ'))
) IN HMSDB.FBKTSPC;

