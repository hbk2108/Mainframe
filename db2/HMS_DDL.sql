-- ============================================================
-- VIEWS
-- ============================================================
CREATE VIEW HMS.V_APPT_DETAIL AS
    SELECT
        A.APPT_ID,
        A.PATIENT_ID,
        A.DOCTOR_ID,
        A.APPT_DATE,
        A.APPT_TIME,
        A.APPT_STATUS,
        A.APPT_NOTES,
        P.PAT_NAME   AS PATIENT_NAME,
        P.PAT_AGE    AS PATIENT_AGE,
        P.PAT_CONTACT AS PAT_CONTACT,
        D.DOC_NAME   AS DOCTOR_NAME,
        D.SPECIALIZ  AS SPECIALIZATION
    FROM HMS.APPOINTMENTS A
    JOIN HMS.PATIENTS P ON A.PATIENT_ID = P.PATIENT_ID
    JOIN HMS.DOCTORS  D ON A.DOCTOR_ID  = D.DOCTOR_ID;

CREATE VIEW HMS.V_PRESC_DETAIL AS
    SELECT
        PR.PRESC_ID,
        PR.APPT_ID,
        PR.PATIENT_ID,
        PR.DOCTOR_ID,
        PR.MEDICINE,
        PR.DOSAGE,
        PR.DURATION,
        PR.DIAGNOSIS,
        PR.PRESC_NOTES,
        PR.CREATED_AT,
        D.DOC_NAME   AS DOCTOR_NAME,
        A.APPT_DATE  AS APPOINTMENT_DATE,
        A.APPT_TIME  AS APPOINTMENT_TIME
    FROM HMS.PRESCRIPTIONS PR
    JOIN HMS.DOCTORS      D ON PR.DOCTOR_ID = D.DOCTOR_ID
    JOIN HMS.APPOINTMENTS A ON PR.APPT_ID   = A.APPT_ID;

CREATE VIEW HMS.V_FEEDBACK_DETAIL AS
    SELECT
        F.FDBK_ID,
        F.PATIENT_ID,
        F.FDBK_MESSAGE,
        F.FDBK_DATE,
        F.FDBK_STATUS,
        F.CREATED_AT,
        P.PAT_NAME AS PATIENT_NAME
    FROM HMS.FEEDBACK F
    JOIN HMS.PATIENTS P ON F.PATIENT_ID = P.PATIENT_ID;

