-- ============================================================
-- TABLE: HMS.BILLING
-- ============================================================
CREATE TABLE HMS.BILLING (
    BILL_ID       INTEGER        NOT NULL GENERATED ALWAYS AS IDENTITY
                                   (START WITH 1 INCREMENT BY 1 CACHE 20),
    PATIENT_ID    INTEGER        NOT NULL,
    AMOUNT        DECIMAL(10,2)  NOT NULL,
